import { once } from 'node:events'
import { link, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { createServer } from 'node:net'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { LinuxVmSandboxProvider, type LinuxVmOptions } from '@keundal/plugin-sandbox-vm'
import { expect, test, vi } from 'vitest'

vi.setConfig({ testTimeout: 240_000, hookTimeout: 130_000 })

test('Linux VM은 호스트의 동시 하드링크·소켓 게시를 격리하고 변경과 재시작 상태를 보존한다', async (t) => {
  const config = process.env.KEUNDAL_TEST_VM_CONFIG
  if (!config)
    throw new Error('Build the guest image and set KEUNDAL_TEST_VM_CONFIG; VM isolation tests never silently skip')
  const options = JSON.parse(await readFile(config, 'utf8')) as LinuxVmOptions
  const directory = await mkdtemp(join(tmpdir(), 'keundal-vm-contract-'))
  t.onTestFinished(() => rm(directory, { recursive: true, force: true }))
  const workspace = join(directory, 'workspace')
  await mkdir(workspace)
  await writeFile(join(workspace, 'input.bin'), Buffer.from([0, 255, 17, 64]))
  await writeFile(join(workspace, 'host-edited.txt'), 'before')
  await writeFile(join(workspace, 'host-deleted.txt'), 'gone')
  const secret = join(directory, 'secret')
  await writeFile(secret, 'outside-secret')
  const worker = join(directory, 'worker.mjs')
  await writeFile(
    worker,
    `
    import { execFileSync } from 'node:child_process'
    import { readFileSync, writeFileSync, existsSync, unlinkSync, mkdirSync } from 'node:fs'
    import { networkInterfaces } from 'node:os'
    const attempt = path => { try { readFileSync(path); return 'escaped' } catch { return 'blocked' } }
    const repository = process.env.HOME + '/repository'
    const worktree = process.env.HOME + '/worktree'
    const homeState = existsSync(worktree + '/retained.txt') ? readFileSync(worktree + '/retained.txt', 'utf8') : null
    if (!existsSync(repository)) {
      mkdirSync(repository)
      const git = args => execFileSync('git', ['-C', repository, ...args])
      git(['init', '-q', '--template='])
      git(['-c', 'user.name=VM fixture', '-c', 'user.email=vm@example.invalid', 'commit', '-qm', 'initial', '--allow-empty'])
      git(['worktree', 'add', '-q', '--detach', worktree, 'HEAD'])
      writeFileSync(worktree + '/retained.txt', 'private-worktree')
    }
    if (execFileSync('git', ['-C', worktree, 'status', '--porcelain']).toString() !== '?? retained.txt\\n')
      throw new Error('Git worktree state was not preserved')
    if (process.env.EXPORT_TEST_MODE === 'recover') {
      if (!readFileSync('zzz-large.bin').equals(Buffer.alloc(8 * 1024 * 1024, 0xa7)))
        throw new Error('Generated bytes were lost after early export rejection')
      unlinkSync('000:reject')
    }
    const old = existsSync('output.bin') ? readFileSync('output.bin').toString('hex') : null
    writeFileSync('output.bin', Buffer.from(process.env.NEXT_OUTPUT, 'hex'))
    console.log(JSON.stringify({ input: readFileSync('input.bin').toString('hex'), old,
      outside: attempt(process.env.OUTSIDE), interfaces: Object.keys(networkInterfaces()),
      hostEdit: readFileSync('host-edited.txt', 'utf8'), hostDeleted: existsSync('host-deleted.txt'),
      uid: process.getuid(), homeState }))
    console.log('keundal-sandbox-ready')
    process.on('SIGTERM', () => {
      if (process.env.EXPORT_TEST_MODE === 'reject') {
        writeFileSync('000:reject', 'invalid host filename')
        writeFileSync('zzz-large.bin', Buffer.alloc(8 * 1024 * 1024, 0xa7))
      }
      console.log(JSON.stringify({ lateLink: attempt('late-link'), lateSocket: existsSync('late.sock') }))
      process.exit(0)
    })
    setInterval(() => console.log('worker-heartbeat'), 100)
  `
  )
  const endpoints: { source: string; target: string; writable: boolean }[] = []
  for (const name of ['api', 'network']) {
    const path =
      process.platform === 'win32'
        ? `\\\\.\\pipe\\keundal-test-${crypto.randomUUID()}`
        : join(directory, `${name}.sock`)
    const server = createServer((socket) => socket.destroy()).listen(path)
    await once(server, 'listening')
    t.onTestFinished(() => {
      server.close()
    })
    endpoints.push({ source: path, target: `/run/keundal/${name}.sock`, writable: false })
  }
  const provider = new LinuxVmSandboxProvider({ ...options, stateDirectory: join(directory, 'state') })
  const start = async (nextOutput = 'fe0012', exportMode = '') => {
    const child = provider.start({
      executable: process.execPath,
      args: ['/run/keundal/worker.mjs'],
      policy: { workspace },
      environment: { OUTSIDE: secret, NEXT_OUTPUT: nextOutput, EXPORT_TEST_MODE: exportMode },
      mounts: [{ source: worker, target: '/run/keundal/worker.mjs', writable: false }, ...endpoints]
    })
    t.onTestFinished(async () => {
      if (child.exitCode === null && child.signalCode === null) await provider.stop(child)
    })
    let output = ''
    let errors = ''
    child.stdout.on('data', (data) => {
      output += String(data)
    })
    child.stderr.on('data', (data) => {
      errors += String(data)
    })
    await new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error(`Guest startup timed out: ${errors}`)), provider.startupTimeoutMs)
      child.once('exit', () => {
        clearTimeout(timer)
        reject(new Error(`Guest exited: ${errors}`))
      })
      child.once('error', reject)
      child.stdout.on('data', () => {
        if (output.includes('keundal-sandbox-ready')) {
          clearTimeout(timer)
          resolve()
        }
      })
    })
    return { child, output: () => output }
  }
  const first = await start()
  const result = JSON.parse(first.output().split('\n')[0]!)
  expect(result).toEqual({
    input: '00ff1140',
    old: null,
    outside: 'blocked',
    interfaces: ['lo'],
    hostEdit: 'before',
    hostDeleted: true,
    uid: 1000,
    homeState: null
  })
  // New host capabilities are published only AFTER the VM imported its independent files.
  await link(secret, join(workspace, 'late-link'))
  await writeFile(join(workspace, 'host-edited.txt'), 'after')
  await rm(join(workspace, 'host-deleted.txt'))
  let lateSocket: ReturnType<typeof createServer> | undefined
  if (process.platform !== 'win32') {
    lateSocket = createServer().listen(join(workspace, 'late.sock'))
    await once(lateSocket, 'listening')
    t.onTestFinished(() => {
      lateSocket!.close()
    })
  }
  await provider.stop(first.child)
  expect(first.output()).toContain('"lateLink":"blocked","lateSocket":false')
  expect(await readFile(secret, 'utf8')).toBe('outside-secret')
  expect(await readFile(join(workspace, 'output.bin'))).toEqual(Buffer.from([254, 0, 18]))
  await rm(join(workspace, 'late-link'))
  if (lateSocket) await new Promise<void>((resolve) => lateSocket!.close(() => resolve()))
  const second = await start('fd0113')
  expect(JSON.parse(second.output().split('\n')[0]!)).toMatchObject({
    old: 'fe0012',
    outside: 'blocked',
    hostEdit: 'after',
    hostDeleted: false,
    homeState: 'private-worktree'
  })
  await writeFile(join(workspace, 'output.bin'), 'host-edit')
  await expect(provider.stop(second.child)).rejects.toThrow('private disk retained')
  expect(await readFile(join(workspace, 'output.bin'), 'utf8')).toBe('host-edit')
  // Resolve the host-side conflict without deleting the guest's unsynced change.
  await writeFile(join(workspace, 'output.bin'), Buffer.from([254, 0, 18]))
  const recovered = await start('fd0113')
  expect(JSON.parse(recovered.output().split('\n')[0]!)).toMatchObject({
    old: 'fd0113',
    hostEdit: 'after',
    hostDeleted: false
  })
  // A vanished HTTP parent takes its diagnostic pipes with it. Those broken
  // sinks must not abort guest shutdown or the final file export.
  const exited = once(recovered.child, 'exit', { signal: AbortSignal.timeout(130_000) })
  recovered.child.stdout.destroy()
  recovered.child.stderr.destroy()
  await new Promise((resolve) => setTimeout(resolve, 500))
  recovered.child.disconnect!()
  expect(await exited).toEqual([0, null])
  await provider.stop(recovered.child)
  expect(await readFile(join(workspace, 'output.bin'))).toEqual(Buffer.from([253, 1, 19]))
  // Reject the first entry while substantial newly-written output is still
  // queued. Shutdown must unwind, not hit the supervisor's 30-second kill timer.
  const rejected = await start('fd0113', 'reject')
  const rejectionTime = Date.now()
  await expect(provider.stop(rejected.child)).rejects.toThrow('private disk retained')
  expect(Date.now() - rejectionTime).toBeLessThan(25_000)
  const repaired = await start('fd0113', 'recover')
  await provider.stop(repaired.child)
  expect((await readFile(join(workspace, 'zzz-large.bin'))).equals(Buffer.alloc(8 * 1024 * 1024, 0xa7))).toBe(true)
})
