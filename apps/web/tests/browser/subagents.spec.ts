import { test, expect, ready, accessible } from './fixtures'

test('서브에이전트 역할을 저장·복원·수정·삭제하고 중복 이름은 저장하지 않는다 @a11y:subagents', async ({ page, context, baseURL }) => {
  test.setTimeout(60_000)
  await context.addCookies([{ name: 'keundal-locale', value: 'en', url: baseURL! }])
  await ready(page, '/settings/subagents')
  await expect(page.getByText('No subagent roles added.')).toBeVisible()
  await accessible(page)
  await page.getByRole('button', { name: 'Add role', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('reviewer')
  await page.getByLabel('Description', { exact: true }).fill('Review changes')
  await page.getByLabel('Instructions', { exact: true }).fill('Check correctness and missing tests.')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Subagent roles saved', { exact: true })).toBeVisible()
  await ready(page, '/settings/subagents')
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('reviewer')
  await expect(page.getByLabel('Instructions', { exact: true })).toHaveValue('Check correctness and missing tests.')
  await accessible(page)

  await page.getByRole('button', { name: 'Add role', exact: true }).click()
  const second = page.getByRole('group', { name: 'Role 2', exact: true })
  await second.getByLabel('Name', { exact: true }).fill('reviewer')
  await second.getByLabel('Description', { exact: true }).fill('Find sources')
  await second.getByLabel('Instructions', { exact: true }).fill('Research the supplied question.')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Each role must have a unique name.')).toHaveCount(2)
  await ready(page, '/settings/subagents')
  await expect(page.getByRole('group', { name: /^Role \d+$/ })).toHaveCount(1)

  await page.getByLabel('Instructions', { exact: true }).fill('Report only actionable risks.')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await ready(page, '/settings/subagents')
  await expect(page.getByLabel('Instructions', { exact: true })).toHaveValue('Report only actionable risks.')
  await page.getByRole('button', { name: 'Remove role 1', exact: true }).click()
  // Removing a draft does not change saved settings until Save.
  await ready(page, '/settings/subagents')
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('reviewer')
  await page.getByRole('button', { name: 'Remove role 1', exact: true }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await ready(page, '/settings/subagents')
  await expect(page.getByText('No subagent roles added.')).toBeVisible()
})
