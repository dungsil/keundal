import { test, expect, ready, accessible } from './fixtures'

test('프리셋의 변수·조건·블록 순서를 미리 보고 저장한 뒤 복제해도 원본을 유지한다', async ({ page }) => {
  await ready(page, '/settings/system-prompt')
  await page.getByRole('button', { name: 'Create preset', exact: true }).click()
  await page.getByLabel('Preset name', { exact: true }).fill('Review')
  await page.getByLabel('Content', { exact: true }).fill('Answer in {{language}}.')
  await page.getByRole('button', { name: 'Add variable', exact: true }).click()
  await page.getByLabel('Variable 1 key', { exact: true }).fill('language')
  await page.getByLabel('Variable 1 value', { exact: true }).fill('Korean')
  const preview = page.getByRole('region', { name: 'Preview', exact: true })
  await expect(preview).toContainText('Answer in Korean.')
  await page.getByLabel('Condition variable (optional)', { exact: true }).fill('language')
  await page.getByLabel('Expected value', { exact: true }).fill('English')
  await expect(preview).not.toContainText('Answer in Korean.')
  await page.getByLabel('Expected value', { exact: true }).fill('Korean')
  await expect(preview).toContainText('Answer in Korean.')
  await page.getByRole('button', { name: 'Move block 1 down', exact: true }).click()
  await expect(preview.getByRole('listitem').first()).toContainText('[Conversation history appears here]')
  await expect(page.getByRole('button', { name: 'Remove block 1', exact: true })).toHaveCount(0)
  await page.getByLabel('Active preset', { exact: true }).selectOption({ label: 'Review' })
  await accessible(page)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Prompt presets saved', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Preset name', { exact: true })).toHaveValue('Review')
  await expect(preview.getByRole('listitem').last()).toContainText('Answer in Korean.')
  await page.getByRole('button', { name: 'Duplicate preset', exact: true }).click()
  await page.getByLabel('Variable 1 value', { exact: true }).fill('English')
  await expect(preview).not.toContainText('Answer in English.')
  await page.getByLabel('Edit preset', { exact: true }).selectOption({ label: 'Review' })
  await expect(page.getByLabel('Variable 1 value', { exact: true })).toHaveValue('Korean')
  await expect(preview).toContainText('Answer in Korean.')
  await page.getByLabel('Content', { exact: true }).fill('{{missing}}')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Unknown variable: missing' }).first()).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Content', { exact: true })).toHaveValue('Answer in {{language}}.')
})
